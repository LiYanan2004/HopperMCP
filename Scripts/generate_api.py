#!/usr/bin/env python3
"""Generate searchable API declarations from the checked-in SDK headers."""
import ast
import json
from pathlib import Path
import re


def selectors_for_declaration(declaration):
    if declaration.startswith("@property"):
        names = [part.strip().split()[-1].lstrip("*") for part in declaration.rstrip(";").split(")", 1)[-1].split(",")]
        result = []
        for name in names:
            if re.fullmatch(r"[A-Za-z_]\w*", name):
                result.append(name)
                if "readonly" not in declaration:
                    result.append("set" + name[0].upper() + name[1:] + ":")
        return result
    body = re.sub(r"^[-+]\s*\([^)]*\)\s*", "", declaration)
    parts = re.findall(r"(\w+)\s*:", body)
    return ["".join(part + ":" for part in parts)] if parts else [body.rstrip(";").strip()]


def main():
    root = Path(__file__).resolve().parents[1]
    headers = root / "HopperSDK"
    if not headers.exists():
        headers = root.parent / "HopperMCP-Upstream/Hopper/Sources/Hopper/include"
    native = []
    constants = []
    for path in sorted(headers.glob("*.h")):
        text = path.read_text()
        cleaned = re.sub(r"/\*.*?\*/|//[^\n]*", lambda match: "".join("\n" if c == "\n" else " " for c in match.group()), text, flags=re.S)
        protocol = re.search(r"@protocol\s+(\w+)(?:\s*<[^>]+>)?\s*\n", cleaned)
        boundaries = [index for marker in ("#pragma mark - Private methods", "#pragma clang diagnostic push") if (index := text.find(marker)) >= 0]
        private_start = min(boundaries) if boundaries else len(text)
        if protocol:
            scope = protocol.group(1)
            extension_header = "Hopper Disassembler SDK" not in text
            declarations = list(re.finditer(r"[-+]\s*\([^)]*\)[^;]+;|@property[^;]+;", cleaned))
            for match in declarations:
                declaration = " ".join(match.group().split())
                for selector in selectors_for_declaration(declaration):
                    native.append({"protocol": scope, "header": path.name, "selector": selector,
                                   "declaration": declaration, "private": extension_header or match.start() >= private_start})
        for enum in re.finditer(r"HP_BEGIN_DECL_(?:ENUM|OPTIONS)\([^,]+,\s*(\w+)\)\s*\{(.*?)\}", text, re.S):
            constants.append({"name": enum.group(1), "header": path.name, "declaration": enum.group(0)})
        for line in text.splitlines():
            if line.startswith("#define "):
                constants.append({"header": path.name, "declaration": line})
    python = []
    python_source = Path("/Applications/Hopper Disassembler v4.app/Contents/Resources/hopper_api.py")
    if python_source.exists():
        for cls in ast.parse(python_source.read_text()).body:
            if isinstance(cls, ast.ClassDef) and cls.name != "HopperStdRedirection":
                for method in cls.body:
                    if isinstance(method, ast.FunctionDef) and not method.name.startswith("__"):
                        python.append({"class": cls.name, "method": method.name, "signature": ast.unparse(method.args),
                                       "documentation": ast.get_docstring(method) or ""})
    resources = root / "Sources/HopperMCPServer/Resources"
    resources.mkdir(parents=True, exist_ok=True)
    if not python_source.exists() and (resources / "api-documentation.json").exists():
        python = json.loads((resources / "api-documentation.json").read_text()).get("python", [])
    (resources / "api-documentation.json").write_text(json.dumps({"native": native, "python": python, "constants": constants}, ensure_ascii=False, indent=2))
    (root / "Plugin/api-native.json").write_text(json.dumps(native, ensure_ascii=False, indent=2))
    tools_json = (resources / "tools.json").read_text()
    documentation_json = (resources / "api-documentation.json").read_text()
    generated = "// Generated by Scripts/generate_api.py.\nimport Foundation\n\nenum EmbeddedCatalog {\n"
    generated += "    static let tools = Data(#\"\"\"\n" + tools_json + "\n\"\"\"#.utf8)\n"
    generated += "    static let documentation = Data(#\"\"\"\n" + documentation_json + "\n\"\"\"#.utf8)\n}\n"
    (root / "Sources/HopperMCPServer/EmbeddedCatalog.swift").write_text(generated)
    print(json.dumps({"native_declarations": len(native), "public_selectors": len({e["selector"] for e in native if not e["private"]}),
                      "python_methods": len(python), "constant_groups": len(constants)}))


if __name__ == "__main__":
    main()
